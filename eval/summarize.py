"""Write reports/SUMMARY.md comparing checkpoint, final and ablation runs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = [("checkpoint", "v0 checkpoint"), ("final", "final"), ("final_ablation_no_boundary_points", "final, ablation: no boundary tickets")]


def row(name, label, split):
    m = json.loads((ROOT / "reports" / name / "metrics.json").read_text())[split]
    d, f = m["decision"], m["finding_quality"]
    inc = d["incomplete_by_type"]
    return (f"| {label} | {d['correct_status']}/{d['total']} | {d['false_pass']}/{d['defective']} | {d['false_block']}/{d['valid']} | "
            f"{inc['valid']}/{d['cases_by_type']['valid']} · {inc['defective']}/{d['cases_by_type']['defective']} · {inc['incomplete']}/{d['cases_by_type']['incomplete']} | "
            f"{f['matched_defect_and_location']}/{f['expected_findings']} | {f['counterexamples_verified']}/{f['counterexamples']} | "
            f"{f['unsupported_blockers']}/{f['blockers_total']} |")


def main():
    out = ["# Evaluation summary", "",
           "Generated by `eval/summarize.py` from `reports/*/metrics.json`. All runs use the same frozen bundles, labels and "
           "settings (`eval/FROZEN.json`). Model results come from the **fake scripted client**; real-model performance was **not measured**.", ""]
    head = ("| Run | Correct status | False pass / defective | False block / valid | INCOMPLETE on valid · defective · incomplete cases | "
            "Defect + location found | Counterexamples verified by oracle | Unsupported blockers / all blockers |\n|---|---|---|---|---|---|---|---|")
    for split, title in (("all", "All 18 bundles"), ("dev", "Development bundles (B01–B11, inspected during development)"),
                         ("heldout", "Held-out bundles (H01–H07, frozen before first run)")):
        out += [f"## {title}", "", head] + [row(n, l, split) for n, l in RUNS] + [""]
    out += ["## Per case", "", "| Bundle | Split | Expected | Checkpoint | Final | Ablation |", "|---|---|---|---|---|---|"]
    ms = {n: json.loads((ROOT / "reports" / n / "metrics.json").read_text())["all"] for n, _ in RUNS}
    for i, c in enumerate(ms["final"]["cases"]):
        cells = []
        for n, _ in RUNS:
            cc = ms[n]["cases"][i]
            cells.append(cc["actual"] + ("" if cc["correct"] else " ✗"))
        out.append(f"| {c['bundle']} | {c['split']} | {c['expected']} | " + " | ".join(cells) + " |")
    r = ms["final"]["resources"]
    out += ["", "## Resource use (final run, 18 bundles, CPU)", "",
            f"- Reviewer runtime (sum of in-process `runtime_s`): {r['runtime_s_total']} s",
            f"- Wall time including one subprocess per bundle: {r['wall_s_total']} s",
            f"- Model calls: {r['model_calls']} (fake client), retries: {r['model_retries']}",
            "- Real model: not run; no live calls, latency or accuracy to report.", ""]
    (ROOT / "reports" / "SUMMARY.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
